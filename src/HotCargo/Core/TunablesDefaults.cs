using System.Collections;
using System.Globalization;
using System.Reflection;
using System.Text;
using Halfling.Serialization;

namespace HotCargo.Core;

/// <summary>
/// Writes tunables.defaults.rules from the C# defaults, so the code stays the only source of default values.
/// tunables.rules holds only the values that differ from the defaults.
/// </summary>
public static class TunablesDefaults
{
    public static void WriteFile()
    {
        string path = Path.Combine(Mod.ModRoot, "tunables.defaults.rules");
        var sb = new StringBuilder();
        sb.AppendLine("// Generated by Hot Cargo at game start from the C# defaults. Do not edit.");
        sb.AppendLine("// Copy a value into tunables.rules to change it. Example: Heat { HeatPerGameMinute = 3 }");
        var defaults = new Tunables();
        TunablesFile.Validate(defaults);
        WriteFields(sb, defaults, 0);
        File.WriteAllText(path, sb.ToString());
    }

    static void WriteFields(StringBuilder sb, object obj, int depth)
    {
        foreach (var field in obj.GetType().GetFields(BindingFlags.Public | BindingFlags.Instance))
        {
            if (field.GetCustomAttribute<SerializeAttribute>() is null) continue;
            WriteValue(sb, field.Name, field.GetValue(obj), depth);
        }
    }

    static void WriteValue(StringBuilder sb, string? name, object? value, int depth)
    {
        string indent = new('\t', depth);
        string prefix = name is null ? indent : $"{indent}{name} = ";
        switch (value)
        {
            case null: throw new InvalidOperationException($"tunable {name} has no default");
            case string s: sb.AppendLine($"{prefix}\"{s.Replace("\"", "\\\"")}\""); break;
            case bool b: sb.AppendLine($"{prefix}{(b ? "true" : "false")}"); break;
            case IFormattable f when value.GetType().IsPrimitive || value is decimal:
                sb.AppendLine($"{prefix}{f.ToString(null, CultureInfo.InvariantCulture)}"); break;
            case IList list when list.Count == 0 || IsScalar(list[0]):
                sb.AppendLine($"{prefix}[{string.Join(", ", list.Cast<object>().Select(Scalar))}]"); break;
            case IList list:
                sb.AppendLine(name is null ? $"{indent}[" : $"{indent}{name}\n{indent}[");
                foreach (var item in list) WriteValue(sb, null, item, depth + 1);
                sb.AppendLine($"{indent}]");
                break;
            default:
                sb.AppendLine(name is null ? $"{indent}{{" : $"{indent}{name}\n{indent}{{");
                WriteFields(sb, value, depth + 1);
                sb.AppendLine($"{indent}}}");
                break;
        }
    }

    static bool IsScalar(object? v) => v is string or bool || (v?.GetType().IsPrimitive ?? false);

    static string Scalar(object v) => v switch
    {
        string s => $"\"{s}\"",
        bool b => b ? "true" : "false",
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => throw new InvalidOperationException($"unsupported tunable value {v.GetType()}"),
    };
}
