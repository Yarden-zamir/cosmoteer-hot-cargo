using System.Collections;
using System.Globalization;
using System.Reflection;
using System.Text;
using Halfling.Serialization;

namespace HotCargo.Core;

/// <summary>
/// Writes tunables as .rules text: tunables.defaults.rules from the C# defaults, so the code stays the only source of default values,
/// and the changed values for tunables.rules (the settings menu writes it).
/// </summary>
public static class TunablesDefaults
{
    public static void WriteFile()
    {
        string path = Path.Combine(Mod.ModRoot, "tunables.defaults.rules");
        var defaults = new Tunables();
        TunablesFile.Validate(defaults);
        File.WriteAllText(path,
            "// Generated by Hot Cargo at game start from the C# defaults. Do not edit.\n" +
            "// Copy a value into tunables.rules to change it. Example: Heat { HeatPerGameMinute = 3 }\n" +
            Write(defaults));
    }

    /// <summary>Every serialized field of the object, as .rules text.</summary>
    public static string Write(object obj)
    {
        var sb = new StringBuilder();
        WriteFields(sb, obj, 0);
        return sb.ToString();
    }

    /// <summary>
    /// Only the values that differ from the defaults, as .rules text for tunables.rules.
    /// The reader builds a nested object from its class defaults, not from the initializer of the parent field
    /// (Mechanics.Siege has other defaults than a new HoldOutTunables). So a nested object is written in part only
    /// when its class defaults equal the parent's default, and in full otherwise. Arrays are always written in full.
    /// </summary>
    public static string WriteChanged(Tunables values)
    {
        var sb = new StringBuilder();
        WriteChangedFields(sb, values, new Tunables(), 0);
        return sb.ToString();
    }

    static IEnumerable<FieldInfo> SerializedFields(Type type) =>
        type.GetFields(BindingFlags.Public | BindingFlags.Instance).Where(f => f.GetCustomAttribute<SerializeAttribute>() is not null);

    static void WriteFields(StringBuilder sb, object obj, int depth)
    {
        foreach (var field in SerializedFields(obj.GetType()))
            WriteValue(sb, field.Name, field.GetValue(obj), depth);
    }

    static void WriteChangedFields(StringBuilder sb, object values, object defaults, int depth)
    {
        foreach (var field in SerializedFields(values.GetType()))
        {
            object? v = field.GetValue(values), d = field.GetValue(defaults);
            if (Same(v, d)) continue;
            bool nestedObject = v is not null && !IsScalar(v) && v is not IList;
            if (nestedObject && Same(d, Activator.CreateInstance(field.FieldType)))
            {
                string indent = new('\t', depth);
                sb.AppendLine($"{indent}{field.Name}\n{indent}{{");
                WriteChangedFields(sb, v!, d!, depth + 1);
                sb.AppendLine($"{indent}}}");
            }
            else WriteValue(sb, field.Name, v, depth);
        }
    }

    /// <summary>Two values are the same when they write the same text. This compares arrays and nested objects by content.</summary>
    static bool Same(object? a, object? b)
    {
        var sa = new StringBuilder();
        var sb = new StringBuilder();
        WriteValue(sa, "v", a, 0);
        WriteValue(sb, "v", b, 0);
        return sa.ToString() == sb.ToString();
    }

    static void WriteValue(StringBuilder sb, string? name, object? value, int depth)
    {
        string indent = new('\t', depth);
        string prefix = name is null ? indent : $"{indent}{name} = ";
        switch (value)
        {
            case null: throw new InvalidOperationException($"tunable {name} has no value");
            case string or bool: sb.AppendLine($"{prefix}{Scalar(value)}"); break;
            case IFormattable when value.GetType().IsPrimitive || value is decimal: sb.AppendLine($"{prefix}{Scalar(value)}"); break;
            case IList list when list.Count == 0 || IsScalar(list[0]):
                sb.AppendLine($"{prefix}[{string.Join(", ", list.Cast<object>().Select(Scalar))}]"); break;
            case IList list:
                sb.AppendLine(name is null ? $"{indent}[" : $"{indent}{name}\n{indent}[");
                foreach (var item in list) WriteValue(sb, null, item, depth + 1);
                sb.AppendLine($"{indent}]");
                break;
            default:
                sb.AppendLine(name is null ? $"{indent}{{" : $"{indent}{name}\n{indent}{{");
                WriteFields(sb, value, depth + 1);
                sb.AppendLine($"{indent}}}");
                break;
        }
    }

    static bool IsScalar(object? v) => v is string or bool || (v?.GetType().IsPrimitive ?? false);

    /// <summary>One scalar in .rules syntax. Floats use the shortest text that reads back to the same value.</summary>
    public static string Scalar(object v) => v switch
    {
        string s => $"\"{s.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"",
        bool b => b ? "true" : "false",
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => throw new InvalidOperationException($"unsupported tunable value {v.GetType()}"),
    };
}
