"""Write GameDeps.props: the NuGet packages that Cosmoteer and HalflingCore reference, at the game's exact versions.

Source of truth: Cosmoteer.deps.json. HalflingPlatformWDX (the Direct3D platform) and the Windows runtime packs are left out.
Run after a game update: uv run gen-deps.py
"""
import json
import pathlib

here = pathlib.Path(__file__).parent
deps = json.loads((here / "../../../.game/Bin/Cosmoteer.deps.json").read_text())
libraries = deps["libraries"]
target = next(t for name, t in deps["targets"].items() if "/" in name)
roots = ["Cosmoteer/1.0.0", "HalflingCore/1.0.0"]

packages = set()
for root in roots:
    for name, version in target[root].get("dependencies", {}).items():
        key = f"{name}/{version}"
        if libraries.get(key, {}).get("type") == "package":
            packages.add((name, version))

items = "\n".join(f'    <PackageReference Include="{n}" Version="{v}" />' for n, v in sorted(packages))
(here / "GameDeps.props").write_text(
    f"<!-- Generated by gen-deps.py from Cosmoteer.deps.json. Do not edit. -->\n<Project>\n  <ItemGroup>\n{items}\n  </ItemGroup>\n</Project>\n"
)
print(items)
